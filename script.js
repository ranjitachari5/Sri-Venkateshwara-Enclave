document.addEventListener("DOMContentLoaded", () => {
  const menuButton = document.getElementById("menuButton");
  const mobileMenu = document.getElementById("mobileMenu");
  const mobileLinks = document.querySelectorAll(".mobile-link");
  const languageButtons = document.querySelectorAll("[data-language-toggle]");
  const contactForm = document.getElementById("contactForm");
  const formStatus = document.getElementById("formStatus");
  let currentLanguage = localStorage.getItem("siteLanguage") || "en";

  document.getElementById("year").textContent = new Date().getFullYear();

  const buildStandaloneEmailUrl = (language) => {
    const body = language === "kn"
      ? "ನಮಸ್ಕಾರ ಶ್ರೀ ವೆಂಕಟೇಶ್ವರ ಎನ್‌ಕ್ಲೇವ್,\n\nನಿಮ್ಮ ಆಸ್ತಿಗಳ ಬಗ್ಗೆ ನನಗೆ ಆಸಕ್ತಿ ಇದೆ. ದಯವಿಟ್ಟು ಹೆಚ್ಚಿನ ವಿವರಗಳೊಂದಿಗೆ ನನ್ನನ್ನು ಸಂಪರ್ಕಿಸಿ.\n\nಧನ್ಯವಾದಗಳು."
      : "Hello Sri Venkateshwara Enclave,\n\nI am interested in your properties. Please contact me with more details.\n\nThank you.";
    const subject = encodeURIComponent("Property Enquiry - Sri Venkateshwara Enclave");
    return `https://mail.google.com/mail/?view=cm&fs=1&to=crazychandrashekhar1@gmail.com&su=${subject}&body=${encodeURIComponent(body)}`;
  };

  const applyLanguage = (language) => {
    const copy = translations[language];
    currentLanguage = language;
    document.documentElement.lang = language === "kn" ? "kn" : "en";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      if (copy[key]) {
        element.textContent = copy[key];
      }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      const key = element.dataset.i18nPlaceholder;
      if (copy[key]) {
        element.setAttribute("placeholder", copy[key]);
      }
    });

    const heroKicker = document.querySelector("#home .section-kicker");
    if (heroKicker) {
      heroKicker.textContent = copy["hero.kicker"];
    }

    const footerLocation = document.querySelector("footer div > p:last-child");
    if (footerLocation) {
      footerLocation.textContent = copy["footer.location"];
    }

    const emailLink = document.querySelector('a[href^="https://mail.google.com/mail/"]');
    if (emailLink) {
      emailLink.href = buildStandaloneEmailUrl(language);
    }

    languageButtons.forEach((button) => {
      button.textContent = language === "en" ? "ಕನ್ನಡ" : "English";
      button.setAttribute("aria-label", language === "en" ? "Switch to Kannada" : "Switch to English");
    });

    localStorage.setItem("siteLanguage", language);
  };

  applyLanguage(currentLanguage);

  languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(currentLanguage === "en" ? "kn" : "en");
      mobileMenu.classList.add("hidden");
      menuButton.setAttribute("aria-expanded", "false");
      menuButton.setAttribute("aria-label", "Open menu");
    });
  });

  menuButton.addEventListener("click", () => {
    const isOpen = !mobileMenu.classList.contains("hidden");
    mobileMenu.classList.toggle("hidden");
    menuButton.setAttribute("aria-expanded", String(!isOpen));
    menuButton.setAttribute("aria-label", isOpen ? "Open menu" : "Close menu");
  });

  mobileLinks.forEach((link) => {
    link.addEventListener("click", () => {
      mobileMenu.classList.add("hidden");
      menuButton.setAttribute("aria-expanded", "false");
      menuButton.setAttribute("aria-label", "Open menu");
    });
  });

  contactForm.addEventListener("submit", (event) => {
    event.preventDefault();

    const name = document.getElementById("name").value.trim();
    const phone = document.getElementById("phone").value.trim();
    const message = document.getElementById("message").value.trim();

    const enquiryMessage = currentLanguage === "kn"
      ? [
          "ನಮಸ್ಕಾರ ಶ್ರೀ ವೆಂಕಟೇಶ್ವರ ಎನ್‌ಕ್ಲೇವ್,",
          "",
          "ನಿಮ್ಮ ಆಸ್ತಿಗಳ ಬಗ್ಗೆ ನನಗೆ ಆಸಕ್ತಿ ಇದೆ. ದಯವಿಟ್ಟು ಹೆಚ್ಚಿನ ವಿವರಗಳೊಂದಿಗೆ ನನ್ನನ್ನು ಸಂಪರ್ಕಿಸಿ.",
          "",
          `ಹೆಸರು: ${name}`,
          `ಫೋನ್ ಸಂಖ್ಯೆ: ${phone}`,
          `ಅವಶ್ಯಕತೆ: ${message}`,
          "",
          "ಧನ್ಯವಾದಗಳು."
        ].join("\n")
      : [
          "Hello Sri Venkateshwara Enclave,",
          "",
          "I am interested in your properties. Please contact me with more details.",
          "",
          `Name: ${name}`,
          `Phone Number: ${phone}`,
          `Requirement: ${message}`,
          "",
          "Thank you."
        ].join("\n");

    formStatus.classList.remove("hidden");

    const whatsappUrl = `https://wa.me/919731878494?text=${encodeURIComponent(enquiryMessage)}`;
    const emailSubject = encodeURIComponent("Property Enquiry - Sri Venkateshwara Enclave");
    const gmailUrl = `https://mail.google.com/mail/?view=cm&fs=1&to=crazychandrashekhar1@gmail.com&su=${emailSubject}&body=${encodeURIComponent(enquiryMessage)}`;

    window.open(whatsappUrl, "_blank", "noopener,noreferrer");
    window.open(gmailUrl, "_blank", "noopener,noreferrer");
  });
});
